const {test,expect} = require('@playwright/test');
const fs = require('node:fs');
const path = require('node:path');

test('complete support, evidence, confirmed handoff and cancellation', async ({page}, testInfo) => {
  const errors=[]; page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await page.locator('#search').click();
  await expect(page.locator('#notice')).toContainText('token válido');
  await page.locator('summary').filter({hasText:'Acesso ao ambiente'}).click();
  await page.locator('#token').fill('browser-test-token-not-for-deployment');
  await page.locator('summary').filter({hasText:'Acesso ao ambiente'}).click();
  await page.locator('#search').click();
  await expect(page.locator('#status')).toContainText('Recebido');
  await page.locator('#ask').click();
  await expect(page.locator('#answer')).toContainText('Orientação geral', {timeout:120000});
  await expect(page.locator('#sources li')).not.toHaveCount(0);
  await expect(page.locator('#trace')).toContainText('lookup_simulation_order');
  await expect(page.locator('#handoff')).toBeDisabled();
  await page.locator('#handoff-consent').check();
  await page.locator('#handoff').click();
  await expect(page.locator('#handoff-result')).toContainText('fila local');
  await page.locator('#refresh-queue').click();
  await expect(page.locator('#queue li')).toHaveCount(1);
  fs.mkdirSync('docs/demo',{recursive:true});
  await page.screenshot({path:'docs/demo/supportops-desktop.png',fullPage:true});
  await page.locator('#propose').click();
  await expect(page.locator('#review')).toBeVisible();
  await expect(page.locator('#confirm')).toBeDisabled();
  await page.locator('#consent').check();
  await page.locator('#confirm').click();
  await expect(page.locator('#status')).toContainText('Cancelado');
  await page.locator('#request-type').selectOption('order_status');
  await page.locator('#ask').click();
  await expect(page.locator('#answer')).toContainText('cancelado');
  await expect(page.locator('#trace')).toContainText('"version": 2');
  await page.reload();
  await page.locator('summary').filter({hasText:'Acesso ao ambiente'}).click();
  await page.locator('#token').fill('browser-test-token-not-for-deployment');
  await page.locator('#search').click();
  await expect(page.locator('#status')).toContainText('Cancelado');
  expect(errors).toEqual([]);
  const video = page.video();
  await page.close();
  await video.saveAs('docs/demo/supportops-demo.webm');
});

test('mobile layout and missing-order feedback', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await page.locator('summary').filter({hasText:'Acesso ao ambiente'}).click();
  await page.locator('#token').fill('browser-test-token-not-for-deployment');
  await page.locator('#order').fill('DEMO-9999');
  await page.locator('#search').click();
  await expect(page.locator('#notice')).toContainText('não encontrado');
  await page.locator('#order').fill('DEMO-1002');
  await page.locator('#search').click();
  await expect(page.locator('#status')).toContainText('Em preparo');
  await expect(page.locator('#propose')).toBeHidden();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({path:'docs/demo/supportops-mobile.png',fullPage:true});
});
